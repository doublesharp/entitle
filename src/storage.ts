import { createHash } from "node:crypto";
import { Readable, Transform } from "node:stream";
import { createReadStream, createWriteStream } from "node:fs";
import { rm } from "node:fs/promises";
import { pipeline } from "node:stream/promises";
import { hashArtifactFile } from "./artifact-streams.ts";
import {
  S3Client,
  PutObjectCommand,
  GetObjectCommand,
  DeleteObjectCommand,
  HeadBucketCommand,
} from "@aws-sdk/client-s3";
import { AppError, check } from "./errors.ts";

export const DEFAULT_ARTIFACT_BYTES = 25 * 1024 * 1024;
export const MAX_ARTIFACT_BYTES = 100 * 1024 * 1024;
export const DEFAULT_NATIVE_ARTIFACT_BYTES = 100 * 1024 * 1024;
export const MAX_NATIVE_ARTIFACT_BYTES = 2048 * 1024 * 1024;
export interface ArtifactStore {
  putFile?(
    tenantId: string,
    releaseId: string,
    file: string,
    checksum: string,
    size: number,
  ): Promise<void>;
  getToFile?(
    tenantId: string,
    releaseId: string,
    checksum: string,
    size: number,
    destination: string,
    signal?: AbortSignal,
    onProgress?: (bytes: number) => void,
  ): Promise<void>;
  put(
    tenantId: string,
    releaseId: string,
    bytes: Buffer,
    checksum: string,
  ): Promise<void>;
  get(
    tenantId: string,
    releaseId: string,
    checksum: string,
    size: number,
  ): Promise<Buffer>;
  delete(tenantId: string, releaseId: string): Promise<void>;
  ready(): Promise<void>;
}
export interface ArtifactStoreOptions {
  maxBytes?: number;
}
export interface S3ArtifactStoreOptions extends ArtifactStoreOptions {
  maxNativeBytes?: number;
  bucket: string;
  region: string;
  endpoint?: string;
  credentials?: {
    accessKeyId: string;
    secretAccessKey: string;
    sessionToken?: string;
  };
  forcePathStyle?: boolean;
  allowInsecureLocalDevelopment?: boolean;
  timeoutMs?: number;
  minBytesPerSecond?: number;
}
function byteLimit(options: ArtifactStoreOptions) {
  const limit = options.maxBytes ?? DEFAULT_ARTIFACT_BYTES;
  check(
    Number.isSafeInteger(limit) && limit > 0 && limit <= MAX_ARTIFACT_BYTES,
    500,
    "storage_configuration",
    "Invalid artifact storage configuration.",
  );
  return limit;
}
// IDs are generated by this service. "primary" is the explicit migration tenant.
// Never accept slugs, uploaded filenames or arbitrary caller-selected object keys.
function objectKey(tenantId: string, releaseId: string) {
  const uuid = /^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/;
  check(
    (tenantId === "primary" || uuid.test(tenantId)) && uuid.test(releaseId),
    400,
    "invalid_artifact_key",
    "Invalid artifact identifier.",
  );
  return `tenants/${tenantId}/releases/${releaseId}.zip`;
}
function metadata(checksum: string, size: number, limit: number) {
  check(
    /^[a-f0-9]{64}$/.test(checksum) &&
      Number.isSafeInteger(size) &&
      size > 0 &&
      size <= limit,
    400,
    "invalid_artifact",
    "Invalid artifact size or checksum.",
  );
}
function integrity(bytes: Buffer, checksum: string, size: number) {
  check(
    bytes.length === size &&
      createHash("sha256").update(bytes).digest("hex") === checksum,
    503,
    "artifact_integrity",
    "Release artifact failed integrity verification.",
  );
}
function unavailable() {
  return new AppError(
    503,
    "storage_unavailable",
    "Artifact storage is unavailable.",
  );
}
function exists() {
  return new AppError(
    409,
    "artifact_exists",
    "Release artifact already exists.",
  );
}

export class S3ArtifactStore implements ArtifactStore {
  private readonly client: S3Client;
  private readonly bucket: string;
  private readonly limit: number;
  private readonly nativeLimit: number;
  private readonly timeoutMs: number;
  private readonly minBytesPerSecond: number;
  constructor(options: S3ArtifactStoreOptions) {
    this.limit = byteLimit(options);
    this.nativeLimit = options.maxNativeBytes ?? DEFAULT_NATIVE_ARTIFACT_BYTES;
    check(
      Number.isSafeInteger(this.nativeLimit) &&
        this.nativeLimit > 0 &&
        this.nativeLimit <= MAX_NATIVE_ARTIFACT_BYTES,
      500,
      "storage_configuration",
      "Invalid native artifact storage limit.",
    );
    this.timeoutMs = options.timeoutMs ?? 15000;
    this.minBytesPerSecond = options.minBytesPerSecond ?? 1024 * 1024;
    check(
      Number.isSafeInteger(this.timeoutMs) &&
        this.timeoutMs > 0 &&
        this.timeoutMs <= 120000 &&
        Number.isSafeInteger(this.minBytesPerSecond) &&
        this.minBytesPerSecond >= 64 * 1024 &&
        this.minBytesPerSecond <= 64 * 1024 * 1024 &&
        /^[a-z0-9][a-z0-9.-]{1,61}[a-z0-9]$/.test(options.bucket) &&
        options.region.trim().length > 0,
      500,
      "storage_configuration",
      "Invalid artifact storage configuration.",
    );
    if (options.endpoint !== undefined) {
      let endpoint: URL;
      try {
        endpoint = new URL(options.endpoint);
      } catch {
        throw new AppError(
          500,
          "storage_configuration",
          "Invalid artifact storage configuration.",
        );
      }
      check(
        (endpoint.protocol === "https:" ||
          (endpoint.protocol === "http:" &&
            options.allowInsecureLocalDevelopment === true &&
            process.env.NODE_ENV !== "production")) &&
          !endpoint.username &&
          !endpoint.password &&
          !endpoint.href.includes("?") &&
          !endpoint.href.includes("#"),
        500,
        "storage_configuration",
        "Invalid artifact storage configuration.",
      );
    }
    this.bucket = options.bucket;
    this.client = new S3Client({
      region: options.region,
      ...(options.endpoint === undefined ? {} : { endpoint: options.endpoint }),
      ...(options.credentials === undefined
        ? {}
        : { credentials: { ...options.credentials } }),
      forcePathStyle: options.forcePathStyle ?? false,
      maxAttempts: 1,
      followRegionRedirects: false,
      requestHandler: {
        connectionTimeout: this.timeoutMs,
        requestTimeout: this.timeoutMs,
        throwOnRequestTimeout: true,
        socketTimeout: this.timeoutMs,
      },
    });
  }
  private transferTimeout(size: number) {
    return this.timeoutMs + Math.ceil((1000 * size) / this.minBytesPerSecond);
  }
  private async operation<T>(
    work: (
      signal: AbortSignal,
      body: (stream: Readable) => void,
      progress: () => void,
    ) => Promise<T>,
    mode: "control" | "upload" | "download" = "control",
    size = 0,
    externalSignal?: AbortSignal,
  ): Promise<T> {
    const controller = new AbortController();
    let stream: Readable | undefined;
    let timer: NodeJS.Timeout | undefined;
    let idleTimer: NodeJS.Timeout | undefined;
    let expire!: () => void;
    const deadline = new Promise<never>((_resolve, reject) => {
      expire = () => {
        controller.abort();
        stream?.destroy();
        reject(unavailable());
      };
      timer = setTimeout(expire, this.transferTimeout(size));
    });
    externalSignal?.addEventListener("abort", expire, { once: true });
    if (externalSignal?.aborted) expire();
    const progress = () => {
      clearTimeout(idleTimer);
      idleTimer = setTimeout(expire, this.timeoutMs);
    };
    if (mode === "download") progress();
    try {
      return await Promise.race([
        work(
          controller.signal,
          (value) => {
            if (controller.signal.aborted) {
              value.destroy();
              throw unavailable();
            }
            stream = value;
            progress();
          },
          progress,
        ),
        deadline,
      ]).finally(() => {
        externalSignal?.removeEventListener("abort", expire);
        clearTimeout(timer);
        clearTimeout(idleTimer);
      });
    } catch (error) {
      stream?.destroy();
      if (error instanceof AppError) throw error;
      const status = (
        error as { $metadata?: { httpStatusCode?: number } } | null | undefined
      )?.$metadata?.httpStatusCode;
      if (mode === "upload" && (status === 409 || status === 412))
        throw exists();
      throw unavailable();
    }
  }
  // MinIO can close a keepalive socket after rejecting an unread PUT body.
  // A reset before read response headers is safe to retry once. Both attempts
  // remain inside the operation deadline; writes and response streams never retry.
  private async safeRead<T>(
    request: () => Promise<T>,
    signal: AbortSignal,
  ): Promise<T> {
    try {
      return await request();
    } catch (error) {
      if (
        (error as { code?: string } | null | undefined)?.code !==
          "ECONNRESET" ||
        signal.aborted
      )
        throw error;
      return request();
    }
  }
  async ready(): Promise<void> {
    await this.operation(async (signal) => {
      await this.safeRead(
        () =>
          this.client.send(new HeadBucketCommand({ Bucket: this.bucket }), {
            abortSignal: signal,
          }),
        signal,
      );
    });
  }
  async put(
    tenantId: string,
    releaseId: string,
    bytes: Buffer,
    checksum: string,
  ): Promise<void> {
    const Key = objectKey(tenantId, releaseId);
    metadata(checksum, bytes.length, this.limit);
    const body = Buffer.from(bytes);
    integrity(body, checksum, body.length);
    await this.operation(
      async (signal) => {
        await this.client.send(
          new PutObjectCommand({
            Bucket: this.bucket,
            Key,
            Body: body,
            ContentLength: body.length,
            ContentType: "application/zip",
            ChecksumSHA256: Buffer.from(checksum, "hex").toString("base64"),
            IfNoneMatch: "*",
          }),
          {
            abortSignal: signal,
            requestTimeout: this.transferTimeout(body.length),
          },
        );
      },
      "upload",
      body.length,
    );
  }
  async get(
    tenantId: string,
    releaseId: string,
    checksum: string,
    size: number,
  ): Promise<Buffer> {
    const Key = objectKey(tenantId, releaseId);
    metadata(checksum, size, MAX_ARTIFACT_BYTES);
    return this.operation(
      async (signal, register, progress) => {
        const response = await this.safeRead(
          () =>
            this.client.send(
              new GetObjectCommand({ Bucket: this.bucket, Key }),
              { abortSignal: signal },
            ),
          signal,
        );
        const body = response.Body;
        if (!(body instanceof Readable)) throw unavailable();
        register(body);
        check(
          response.ContentLength === undefined ||
            response.ContentLength === size,
          503,
          "artifact_integrity",
          "Release artifact failed integrity verification.",
        );
        const chunks: Buffer[] = [];
        let length = 0;
        const hash = createHash("sha256");
        for await (const value of body) {
          progress();
          const chunk = Buffer.from(value as Uint8Array);
          length += chunk.length;
          check(
            length <= size,
            503,
            "artifact_integrity",
            "Release artifact failed integrity verification.",
          );
          chunks.push(chunk);
          hash.update(chunk);
        }
        check(
          length === size && hash.digest("hex") === checksum,
          503,
          "artifact_integrity",
          "Release artifact failed integrity verification.",
        );
        return Buffer.concat(chunks, length);
      },
      "download",
      size,
    );
  }
  async putFile(
    tenantId: string,
    releaseId: string,
    file: string,
    checksum: string,
    size: number,
  ): Promise<void> {
    const Key = objectKey(tenantId, releaseId);
    metadata(checksum, size, this.nativeLimit);
    check(
      (await hashArtifactFile(file, size)).checksum === checksum,
      503,
      "artifact_integrity",
      "Artifact failed integrity verification.",
    );
    await this.operation(
      async (signal, register, progress) => {
        const source = createReadStream(file, { end: size - 1 });
        const body = source.pipe(
          new Transform({
            transform(chunk: Buffer, _encoding, callback) {
              progress();
              callback(null, chunk);
            },
          }),
        );
        source.on("error", (error) => body.destroy(error));
        register(body);
        try {
          await this.client.send(
            new PutObjectCommand({
              Bucket: this.bucket,
              Key,
              Body: body,
              ContentLength: size,
              ContentType: "application/octet-stream",
              ChecksumSHA256: Buffer.from(checksum, "hex").toString("base64"),
              IfNoneMatch: "*",
            }),
            { abortSignal: signal, requestTimeout: this.transferTimeout(size) },
          );
        } finally {
          source.destroy();
          body.destroy();
        }
      },
      "upload",
      size,
    );
  }
  async getToFile(
    tenantId: string,
    releaseId: string,
    checksum: string,
    size: number,
    destination: string,
    externalSignal?: AbortSignal,
    onProgress?: (bytes: number) => void,
  ): Promise<void> {
    const Key = objectKey(tenantId, releaseId);
    metadata(checksum, size, MAX_NATIVE_ARTIFACT_BYTES);
    let writing: Promise<void> | undefined;
    let owned = false;
    try {
      await this.operation(
        async (signal, register, progress) => {
          const response = await this.safeRead(
            () =>
              this.client.send(
                new GetObjectCommand({ Bucket: this.bucket, Key }),
                { abortSignal: signal },
              ),
            signal,
          );
          if (!(response.Body instanceof Readable)) throw unavailable();
          register(response.Body);
          check(
            response.ContentLength === undefined ||
              response.ContentLength === size,
            503,
            "artifact_integrity",
            "Artifact length mismatch.",
          );
          let length = 0;
          const hash = createHash("sha256");
          const verify = new Transform({
            transform(chunk: Buffer, _encoding, callback) {
              progress();
              onProgress?.(chunk.length);
              length += chunk.length;
              if (length > size) {
                callback(
                  new AppError(
                    503,
                    "artifact_integrity",
                    "Artifact length mismatch.",
                  ),
                );
                return;
              }
              hash.update(chunk);
              callback(null, chunk);
            },
            flush(callback) {
              callback(
                length === size && hash.digest("hex") === checksum
                  ? null
                  : new AppError(
                      503,
                      "artifact_integrity",
                      "Artifact digest mismatch.",
                    ),
              );
            },
          });
          const output = createWriteStream(destination, {
            flags: "wx",
            mode: 0o600,
          });
          output.once("open", () => {
            owned = true;
          });
          writing = pipeline(response.Body, verify, output, { signal });
          await writing;
        },
        "download",
        size,
        externalSignal,
      );
    } catch (error) {
      if (writing) await writing.catch(() => {});
      if (owned) await rm(destination, { force: true });
      throw error;
    }
  }
  async delete(tenantId: string, releaseId: string): Promise<void> {
    const Key = objectKey(tenantId, releaseId);
    await this.operation(async (signal) => {
      await this.client.send(
        new DeleteObjectCommand({ Bucket: this.bucket, Key }),
        { abortSignal: signal },
      );
    });
  }
}

// Explicit local fixture. Production constructs S3ArtifactStore.
export class InMemoryArtifactStore implements ArtifactStore {
  private readonly objects = new Map<string, Buffer>();
  private readonly limit: number;
  constructor(options: ArtifactStoreOptions = {}) {
    this.limit = byteLimit(options);
  }
  async ready(): Promise<void> {}
  async put(
    tenantId: string,
    releaseId: string,
    bytes: Buffer,
    checksum: string,
  ): Promise<void> {
    const key = objectKey(tenantId, releaseId);
    metadata(checksum, bytes.length, this.limit);
    integrity(bytes, checksum, bytes.length);
    if (this.objects.has(key)) throw exists();
    this.objects.set(key, Buffer.from(bytes));
  }
  async get(
    tenantId: string,
    releaseId: string,
    checksum: string,
    size: number,
  ): Promise<Buffer> {
    const key = objectKey(tenantId, releaseId);
    metadata(checksum, size, MAX_ARTIFACT_BYTES);
    const bytes = this.objects.get(key);
    if (!bytes) throw unavailable();
    integrity(bytes, checksum, size);
    return Buffer.from(bytes);
  }
  async delete(tenantId: string, releaseId: string): Promise<void> {
    this.objects.delete(objectKey(tenantId, releaseId));
  }
}
